// A fan shell with scalloped edge; hinge at x,y, opening towards angle mid.
function fan(x, y, r, spread, mid, n, col) {
  const a0 = mid - spread / 2, step = spread / n;
  const P = (rr, a) => `${f1(x + Math.cos(a) * rr)} ${f1(y + Math.sin(a) * rr)}`;
  let d = `M${x} ${y}L${P(r, a0)}`, ribs = '';
  for (let i = 0; i < n; i++) {
    d += `Q${P(r * 1.17, a0 + (i + 0.5) * step)} ${P(r, a0 + (i + 1) * step)}`;
    if (i < n - 1) ribs += `M${P(r * 0.2, a0 + (i + 1) * step)}L${P(r, a0 + (i + 1) * step)}`;
  }
  return [[`${d}Z`, col], [ribs, null]];
}

