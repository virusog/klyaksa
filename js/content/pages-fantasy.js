function feather(x, y, len, w, a) {
  const c = Math.cos(a), n = Math.sin(a);
  const P = (u, v) => `${f1(x + u * c - v * n)} ${f1(y + u * n + v * c)}`;
  return `M${P(0, 0)}C${P(len * 0.3, -w)} ${P(len * 0.9, -w * 1.15)} ${P(len, 0)}C${P(len * 0.98, w)} ${P(len * 0.3, w)} ${P(0, 0)}Z`;
}
// A tapered tube through joints [x, y, half-width].
function limb(pts) {
  const n = pts.length, A = [], B = [];
  pts.forEach((p, i) => {
    const a = pts[Math.max(i - 1, 0)], b = pts[Math.min(i + 1, n - 1)];
    const dx = b[0] - a[0], dy = b[1] - a[1], l = Math.hypot(dx, dy) || 1;
    A.push([p[0] - (dy / l) * p[2], p[1] + (dx / l) * p[2]]);
    B.push([p[0] + (dy / l) * p[2], p[1] - (dx / l) * p[2]]);
  });
  const run = q => {
    let d = '';
    for (let i = 0; i < q.length - 1; i++) {
      const p0 = q[Math.max(i - 1, 0)], p1 = q[i], p2 = q[i + 1], p3 = q[Math.min(i + 2, q.length - 1)];
      d += `C${f1(p1[0] + (p2[0] - p0[0]) / 6)} ${f1(p1[1] + (p2[1] - p0[1]) / 6)} ${f1(p2[0] - (p3[0] - p1[0]) / 6)} ${f1(p2[1] - (p3[1] - p1[1]) / 6)} ${f1(p2[0])} ${f1(p2[1])}`;
    }
    return d;
  };
  const back = [...B].reverse();
  return `M${f1(A[0][0])} ${f1(A[0][1])}${run(A)}L${f1(back[0][0])} ${f1(back[0][1])}${run(back)}Z`;
}
function leg(pts, col, hoofCol) {
  const e = pts[pts.length - 1], b = pts[pts.length - 2];
  const a = Math.atan2(e[1] - b[1], e[0] - b[0]) - Math.PI / 2;
  const hoof = tf('M-20 -6L20 -6L30 28Q0 40 -30 28Z', e[0], e[1], e[2] / 15, a);
  return [[limb(pts), col], [hoof, hoofCol]];
}

