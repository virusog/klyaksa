function wheel(cx, cy, r, tire, disc, hub, n = 8) {
  const out = [[O(cx, cy, r), tire], [O(cx, cy, r - 19), disc]];
  let d = '';
  for (let i = 0; i < n; i++) {
    const a = (i * 6.2832) / n + 0.2;
    d += `M${f1(cx + Math.cos(a) * r * 0.2)} ${f1(cy + Math.sin(a) * r * 0.2)}L${f1(cx + Math.cos(a) * (r - 19))} ${f1(cy + Math.sin(a) * (r - 19))}`;
  }
  out.push([d, null], [O(cx, cy, r * 0.27), hub]);
  return out;
}

