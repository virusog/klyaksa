const rnd = n => Math.round(n);

// The same line on the other side of the sheet. Works for absolute M, L, C and Q commands.
const mir = d => d.replace(/(-?\d+\.?\d*) (-?\d+\.?\d*)/g, (_, x, y) => `${1000 - x} ${y}`);
const both = d => [d, mir(d)];

// A braid along a bent axis: a zigzag down the middle and round bumps on both sides.
// The zigzag starts on the inner side. Returns [zigzag, inner bumps, outer bumps].
function braid(p0, p1, p2, n, c, w, taper = 0.25) {
  const V = [], out = [];
  for (let j = 0; j <= n; j++) {
    const t = j / n, u = 1 - t, k = 1 - taper * t;
    const x = u * u * p0[0] + 2 * u * t * p1[0] + t * t * p2[0];
    const y = u * u * p0[1] + 2 * u * t * p1[1] + t * t * p2[1];
    let tx = 2 * u * (p1[0] - p0[0]) + 2 * t * (p2[0] - p1[0]);
    let ty = 2 * u * (p1[1] - p0[1]) + 2 * t * (p2[1] - p1[1]);
    const len = Math.hypot(tx, ty);
    tx /= len; ty /= len;
    const side = j % 2 ? -1 : 1;
    V.push([x + ty * c * k * side, y - tx * c * k * side]);
    out.push([ty * side * (w - c) * k / 0.75, -tx * side * (w - c) * k / 0.75]);
  }
  const P = ([x, y]) => `${rnd(x)} ${rnd(y)}`;
  const zig = `M${V.map(P).join('L')}`;
  const bumps = from => {
    let d = `M${P(V[from])}`;
    for (let j = from; j + 2 <= n; j += 2) {
      const a = V[j], b = V[j + 2], o = out[j + 1];
      d += `C${P([a[0] - o[0], a[1] - o[1]])} ${P([b[0] - o[0], b[1] - o[1]])} ${P(b)}`;
    }
    return d;
  };
  return [zig, bumps(0), bumps(1)];
}

