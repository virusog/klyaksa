// A child's head in profile, looking right. Lines are written around the middle of the head
// for a head 100 units in radius; `at` moves, scales and tilts them onto the sheet.
function profile(x, y, s, deg = 0) {
  const c = Math.cos(deg * Math.PI / 180), n = Math.sin(deg * Math.PI / 180);
  const pt = (a, b) => [rnd(x + (a * c - b * n) * s), rnd(y + (a * n + b * c) * s)];
  const at = d => d.replace(/(-?\d+\.?\d*) (-?\d+\.?\d*)/g, (_, a, b) => pt(+a, +b).join(' '));
  return {
    at, pt,
    skull: at('M-58 84C-104 50 -112 -40 -70 -82C-30 -118 50 -112 82 -62C92 -44 97 -24 95 -6Q98 16 118 32Q126 42 112 46L99 49Q102 62 97 72C96 92 80 104 56 104C40 104 30 103 22 100'),
    ear: at('M4 -6C-28 -22 -34 30 -2 34'),
    nape: at('M-2 34C-14 58 -34 76 -58 84'),
    brow: at('M48 -30Q64 -40 82 -30'),
    smile: at('M97 72Q84 90 60 80'),
    eye: E(...pt(64, 4), 4, rnd(9 * s)),
  };
}
