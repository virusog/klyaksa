// A leafy tree top: round bumps that meet in small dips, like a cloud.
function crown(x, y, r, n = 9, seed = 0) {
  const at = (a, q) => `${f1(x + Math.cos(a) * r * q * 1.08)} ${f1(y + Math.sin(a) * r * q * 0.92)}`;
  const step = 6.2832 / n;
  let d = `M${at(seed, 0.84)}`;
  for (let i = 0; i < n; i++) {
    const a = seed + i * step;
    d += `Q${at(a + step / 2, i % 2 ? 1.34 : 1.26)} ${at(a + step, 0.84)}`;
  }
  return `${d}Z`;
}

// ---------- Autumn ----------
function spikes(cx, cy, rx, ry, a0, a1, n, len, sag = 0) {
  let d = '', x0 = 0, y0 = 0, xe = 0, ye = 0;
  for (let i = 0; i <= n * 2; i++) {
    const a = ((a0 + ((a1 - a0) * i) / (n * 2)) * Math.PI) / 180;
    const q = i % 2 ? 1 + len : 1;
    xe = cx + Math.cos(a) * rx * q; ye = cy + Math.sin(a) * ry * q;
    if (!i) { x0 = xe; y0 = ye; }
    d += `${i ? 'L' : 'M'}${f1(xe)} ${f1(ye)}`;
  }
  return sag ? `${d}Q${f1((x0 + xe) / 2)} ${f1((y0 + ye) / 2 + sag)} ${f1(x0)} ${f1(y0)}Z` : `${d}Z`;
}

