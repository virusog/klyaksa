const BLK = '#37374f';
function stick(x0, y0, x1, y1, w, segs, col) {
  const out = [];
  const dx = (x1 - x0) / segs, dy = (y1 - y0) / segs, L = Math.hypot(dx, dy);
  const nx = (-dy / L) * w * 0.5, ny = (dx / L) * w * 0.5;
  for (let i = 0; i < segs; i++) {
    const a = [x0 + dx * i, y0 + dy * i], b = [x0 + dx * (i + 1), y0 + dy * (i + 1)];
    out.push([`M${f1(a[0] + nx)} ${f1(a[1] + ny)}L${f1(b[0] + nx)} ${f1(b[1] + ny)}L${f1(b[0] - nx)} ${f1(b[1] - ny)}L${f1(a[0] - nx)} ${f1(a[1] - ny)}Z`, col]);
  }
  return out;
}

