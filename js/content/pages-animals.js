const f1 = v => +v.toFixed(1);

// Smooth outline through points, closed or open.
function spline(pts, closed) {
  const n = pts.length;
  const at = i => (closed ? pts[(i + n) % n] : pts[Math.max(0, Math.min(n - 1, i))]);
  let d = `M${f1(pts[0][0])} ${f1(pts[0][1])}`;
  for (let i = 0; i < (closed ? n : n - 1); i++) {
    const [p0, p1, p2, p3] = [at(i - 1), at(i), at(i + 1), at(i + 2)];
    d += `C${f1(p1[0] + (p2[0] - p0[0]) / 6)} ${f1(p1[1] + (p2[1] - p0[1]) / 6)} ${f1(p2[0] - (p3[0] - p1[0]) / 6)} ${f1(p2[1] - (p3[1] - p1[1]) / 6)} ${f1(p2[0])} ${f1(p2[1])}`;
  }
  return closed ? `${d}Z` : d;
}
const blob = pts => spline(pts, true);
const line = pts => spline(pts, false);

// An ellipse made of curves, so it can be moved, flipped and turned like everything else.
function el(cx, cy, rx, ry, rot = 0) {
  const k = 0.5523, a = (rot * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a);
  const P = (u, v) => `${f1(cx + u * c - v * s)} ${f1(cy + u * s + v * c)}`;
  return `M${P(rx, 0)}C${P(rx, ry * k)} ${P(rx * k, ry)} ${P(0, ry)}C${P(-rx * k, ry)} ${P(-rx, ry * k)} ${P(-rx, 0)}C${P(-rx, -ry * k)} ${P(-rx * k, -ry)} ${P(0, -ry)}C${P(rx * k, -ry)} ${P(rx, -ry * k)} ${P(rx, 0)}Z`;
}
const box = (x, y, w, h) => `M${x} ${y}L${x + w} ${y}L${x + w} ${y + h}L${x} ${y + h}Z`;

// Moves a path made only of absolute M, L, C, Q and Z commands.
function move(d, x, y, s = 1, flip = 1, rot = 0) {
  const a = (rot * Math.PI) / 180, c = Math.cos(a), n = Math.sin(a);
  return d.replace(/(-?\d*\.?\d+) (-?\d*\.?\d+)/g, (_, u, v) => {
    const px = +u * s * flip, py = +v * s;
    return `${f1(x + px * c - py * n)} ${f1(y + px * n + py * c)}`;
  });
}
const place = (shapes, x, y, s = 1, flip = 1, rot = 0) => shapes.map(([d, c]) => [move(d, x, y, s, flip, rot), c]);
const mir = d => move(d, 0, 0, 1, -1);
const both = (d, c) => [[d, c], [mir(d), c]];
