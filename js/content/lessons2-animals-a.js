// The same line seen in a mirror at x=500 (for paths made of M, L, C and Q only).
const twin = d => d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (m, x, y) => `${1000 - x} ${y}`);
const both = (...lines) => lines.flatMap(d => [d, twin(d)]);

// A point on a cubic curve, as [x, y].
const on = (c, t) => [0, 1].map(k => (1 - t) ** 3 * c[0][k] + 3 * (1 - t) ** 2 * t * c[1][k] + 3 * (1 - t) * t * t * c[2][k] + t ** 3 * c[3][k]);
const xy = p => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`;
const curve = (...cs) => cs.map((c, i) => `${i ? '' : `M${c[0].join(' ')}`}C${c[1].join(' ')} ${c[2].join(' ')} ${c[3].join(' ')}`).join('');

// A chain of joined curves: a start point, then three points for every next piece.
const chain = (start, ...rest) => rest.map((c, i) => [i ? rest[i - 1][2] : start, ...c]);

// A fluffy edge: locks of fur that follow a chain of curves and lean towards its end.
// With an end point the last lock closes into a soft tip there; with back the notches stay shallow.
function fur(cs, n, h, side, { lean = 0.5, from = 0, to = 1, end, back = 0 } = {}) {
  const at = u => {
    const k = Math.min(cs.length - 1, Math.floor(u * cs.length));
    return on(cs[k], u * cs.length - k);
  };
  let d = '', start = at(from);
  for (let i = 0; i < n; i++) {
    const p = at(from + ((to - from) * i) / n), q = at(from + ((to - from) * (i + 1)) / n);
    const len = Math.hypot(q[0] - p[0], q[1] - p[1]) || 1;
    const dx = (q[0] - p[0]) / len, dy = (q[1] - p[1]) / len;
    const nx = dy * side, ny = -dx * side;
    const k = i === n - 1 && !end ? 0 : back;
    const tip = [q[0] + (nx + dx * lean) * h, q[1] + (ny + dy * lean) * h];
    const ctl = [(start[0] + q[0]) / 2 + nx * h, (start[1] + q[1]) / 2 + ny * h];
    const stop = [q[0] + nx * h * k, q[1] + ny * h * k];
    const dip = [q[0] + (nx * (0.45 + k * 0.5) + dx * lean * 0.15) * h, q[1] + (ny * (0.45 + k * 0.5) + dy * lean * 0.15) * h];
    d += `${i ? '' : `M${xy(start)}`}Q${xy(ctl)} ${xy(tip)}Q${xy(dip)} ${xy(stop)}`;
    start = stop;
    if (end && i === n - 1) d += `Q${xy([(q[0] + end[0]) / 2 + nx * h * 0.7, (q[1] + end[1]) / 2 + ny * h * 0.7])} ${xy(end)}`;
  }
  return d;
}

// A small oak leaf from its stalk to its tip, with three round lobes on each side.
function oakLeaf(x0, y0, x1, y1, w) {
  const ux = x1 - x0, uy = y1 - y0, len = Math.hypot(ux, uy), vx = (-uy / len) * w, vy = (ux / len) * w;
  const P = (s, k) => `${(x0 + ux * s + vx * k).toFixed(1)} ${(y0 + uy * s + vy * k).toFixed(1)}`;
  const half = k => [[0.12, 1.5, 0.3, 0.35], [0.4, 1.7, 0.55, 0.38], [0.66, 1.5, 0.8, 0.32]].map(([a, b, c, e]) => `Q${P(a, b * k)} ${P(c, e * k)}`).join('');
  const back = k => [[0.66, 1.5, 0.55, 0.38], [0.4, 1.7, 0.3, 0.35], [0.12, 1.5, 0, 0]].map(([a, b, c, e]) => `Q${P(a, b * k)} ${P(c, e * k)}`).join('');
  return `M${P(0, 0)}${half(1)}Q${P(0.92, 0.9)} ${P(1, 0)}Q${P(0.92, -0.9)} ${P(0.8, -0.32)}${back(-1)}Z`;
}

