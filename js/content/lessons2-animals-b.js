import { O, E, S } from '../art.js';

const f = n => +n.toFixed(1);
const xy = p => `${f(p[0])} ${f(p[1])}`;

// The same line seen in a mirror at x=500 (for paths made of M, L, C and Q only).
const twin = d => d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (m, x, y) => `${f(1000 - x)} ${y}`);
const both = (...lines) => lines.flatMap(d => [d, twin(d)]);
// A circle and its mirror twin.
const pair = (x, y, r) => [O(x, y, r), O(1000 - x, y, r)];

// A point on a cubic curve, as [x, y].
const on = (c, t) => [0, 1].map(k => (1 - t) ** 3 * c[0][k] + 3 * (1 - t) ** 2 * t * c[1][k] + 3 * (1 - t) * t * t * c[2][k] + t ** 3 * c[3][k]);
const curve = c => `M${c[0].join(' ')}C${c[1].join(' ')} ${c[2].join(' ')} ${c[3].join(' ')}`;
const mid = (a, b, k = 0.5) => [a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k];

// A smooth line through a list of points.
function through(pts) {
  let d = `M${xy(pts[0])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const a = pts[i - 1] || pts[i], b = pts[i], c = pts[i + 1], e = pts[i + 2] || c;
    d += `C${xy([b[0] + (c[0] - a[0]) / 6, b[1] + (c[1] - a[1]) / 6])} ${xy([c[0] - (e[0] - b[0]) / 6, c[1] - (e[1] - b[1]) / 6])} ${xy(c)}`;
  }
  return d;
}

// ——— Swallowtail butterfly (left half; the right half is its mirror twin) ———
const FW_MARGIN = [[80, 165], [105, 235], [160, 320], [235, 390]];
const FW_BAND = [[128, 84], [150, 180], [210, 300], [288, 388]];
// A spot in the border band: halfway from the wing edge to the nearest point of the band line.
const fwSpot = (a, r) => {
  const p = on(FW_MARGIN, a);
  let best = FW_BAND[0];
  for (let t = 0; t <= 1; t += 0.02) {
    const q = on(FW_BAND, t);
    if (Math.hypot(q[0] - p[0], q[1] - p[1]) < Math.hypot(best[0] - p[0], best[1] - p[1])) best = q;
  }
  return pair(...mid(p, best).map(Math.round), r);
};
const fwVein = (y, t, bend) => {
  const q = on(FW_BAND, t), x = y === 290 ? 475 : 477;
  return `M${x} ${y}Q${f((x + q[0]) / 2)} ${f((y + q[1]) / 2 + bend)} ${xy(q)}`;
};

// A row of soft bumps from one point to another; h is how far they bulge (to the right of the way).
function bumps(a, b, n, h) {
  const len = Math.hypot(b[0] - a[0], b[1] - a[1]), nx = (-(b[1] - a[1]) / len) * h, ny = ((b[0] - a[0]) / len) * h;
  let d = `M${xy(a)}`;
  for (let i = 0; i < n; i++) {
    const p = mid(a, b, (i + 0.5) / n);
    d += `Q${xy([p[0] + nx, p[1] + ny])} ${xy(mid(a, b, (i + 1) / n))}`;
  }
  return d;
}

// A pointed leaf from its stem to its tip, with the middle vein.
function leaf(b, t, w) {
  const len = Math.hypot(t[0] - b[0], t[1] - b[1]), nx = (-(t[1] - b[1]) / len) * w, ny = ((t[0] - b[0]) / len) * w;
  const p = mid(b, t, 0.25), q = mid(b, t, 0.7);
  return [`M${xy(b)}C${xy([p[0] + nx, p[1] + ny])} ${xy([q[0] + nx, q[1] + ny])} ${xy(t)}C${xy([q[0] - nx, q[1] - ny])} ${xy([p[0] - nx, p[1] - ny])} ${xy(b)}Z`,
    `M${xy(b)}L${xy(mid(b, t, 0.78))}`];
}

// A wavy water line: n waves between x0 and x1, each amp high.
function waves(x0, x1, y, amp, n) {
  const w = (x1 - x0) / n;
  let d = `M${x0} ${y}`;
  for (let i = 0; i < n; i++) {
    const a = x0 + i * w;
    d += `Q${f(a + w / 4)} ${y - amp * 2} ${f(a + w / 2)} ${y}Q${f(a + (w * 3) / 4)} ${y + amp * 2} ${f(a + w)} ${y}`;
  }
  return d;
}

// A falling drop with a sharp top.
const drop = (x, y, s) => `M${x} ${f(y - s * 1.6)}C${f(x + s * 0.5)} ${f(y - s * 0.5)} ${x + s} ${f(y + s * 0.1)} ${x + s} ${f(y + s * 0.4)}C${x + s} ${f(y + s * 1.2)} ${x - s} ${f(y + s * 1.2)} ${x - s} ${f(y + s * 0.4)}C${x - s} ${f(y + s * 0.1)} ${f(x - s * 0.5)} ${f(y - s * 0.5)} ${x} ${f(y - s * 1.6)}Z`;

// The middle line of a tentacle: it leaves p heading deg (90 is down, 180 is left) and is built from parts
// [length, turn at the start, turn at the end], the turn in degrees per 100 units, so it never has a kink.
function spine(p, deg, parts) {
  const c = [[p[0], p[1], deg]];
  let [x, y] = p, a = deg;
  for (const [len, k0, k1] of parts) {
    const n = Math.round(len / 2);
    for (let i = 0; i < n; i++) {
      a += ((k0 + ((k1 - k0) * (i + 0.5)) / n) * 2) / 100;
      x += Math.cos((a * Math.PI) / 180) * 2;
      y += Math.sin((a * Math.PI) / 180) * 2;
      c.push([x, y, a]);
    }
  }
  return c;
}
const polar = (p, deg, r) => [p[0] + Math.cos((deg * Math.PI) / 180) * r, p[1] + Math.sin((deg * Math.PI) / 180) * r];

// A tentacle as one line: down one side, around the round tip and back. It is w0 wide at the root and w1 at the tip.
function arm(c, w0, w1) {
  const n = c.length - 1, left = [], right = [];
  for (let i = 0; i <= n; i += 5) {
    const w = (w0 + (w1 - w0) * (i / n) ** 1.3) / 2;
    left.push(polar(c[i], c[i][2] + 90, w));
    right.push(polar(c[i], c[i][2] - 90, w));
  }
  const e = c[n], cap = [55, 0, -55].map(t => polar(e, e[2] + t, t ? w1 / 2 : w1 * 0.7));
  return through([...left, ...cap, ...right.reverse()]);
}
// A sucker on the middle line of a tentacle, k of the way along it, with its mirror twin.
const sucker = (c, k, r) => pair(...c[Math.round(k * (c.length - 1))].slice(0, 2).map(Math.round), r);

// The four left tentacles start side by side on the round underside of the body.
const ROOTS = [[500, 450], [435, 441], [378, 415], [335, 375], [313, 326]];
const root = i => {
  const a = ROOTS[i + 1], b = ROOTS[i];
  return [mid(a, b), (Math.atan2(b[1] - a[1], b[0] - a[0]) * 180) / Math.PI + 90, Math.hypot(b[0] - a[0], b[1] - a[1])];
};
const tentacle = (i, parts) => {
  const [p, deg, w] = root(i), c = spine(p, deg, parts);
  return { c, d: arm(c, w, 13) };
};
