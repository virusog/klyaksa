import { O, E, R, S, heartD, starD } from '../art.js';

// Moves every "x y" pair of a path made only of absolute M, L, C, Q and Z.
const map = (d, f) => d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (_, x, y) => f(+x, +y).map(v => +v.toFixed(1)).join(' '));
// The twin of a path on the other side of the axis x = 500.
const mir = d => map(d, (x, y) => [1000 - x, y]);
// Each path followed by its twin, for drawings that are symmetric.
const both = (...ds) => ds.flatMap(d => [d, mir(d)]);
// Turn about (cx, cy) by deg (negative lifts the right side), scale, then shift.
const turn = (cx, cy, deg, k = 1, dx = 0, dy = 0) => {
  const c = Math.cos((deg * Math.PI) / 180) * k, s = Math.sin((deg * Math.PI) / 180) * k;
  return (x, y) => [cx + (x - cx) * c - (y - cy) * s + dx, cy + (x - cx) * s + (y - cy) * c + dy];
};

// A point on a circle, and a flower whose petals start and end on its round middle.
const P = (x, y, r, a) => `${(x + Math.cos(a) * r).toFixed(1)} ${(y + Math.sin(a) * r).toFixed(1)}`;
const petalD = (x, y, r0, rc, n, i) => {
  const w = Math.PI / n, a = -Math.PI / 2 + i * 2 * w;
  return `M${P(x, y, r0, a - w)}C${P(x, y, rc, a - w)} ${P(x, y, rc, a + w)} ${P(x, y, r0, a + w)}`;
};
const ringD = (x, y, r0, rc, n) => {
  const w = Math.PI / n;
  let d = `M${P(x, y, r0, -Math.PI / 2 - w)}`;
  for (let i = 0; i < n; i++) {
    const a = -Math.PI / 2 + i * 2 * w;
    d += `C${P(x, y, rc, a - w)} ${P(x, y, rc, a + w)} ${P(x, y, r0, a + w)}`;
  }
  return `${d}Z`;
};

// A cloud: a flat bottom and four bumps, the second one the tallest.
const cloud = (x, y, w) => {
  const n = v => +(v * w).toFixed(1);
  return `M${x - w} ${y}a${n(0.28)} ${n(0.28)} 0 0 1 ${n(0.3)} ${n(-0.42)}a${n(0.42)} ${n(0.42)} 0 0 1 ${n(0.78)} ${n(-0.2)}a${n(0.34)} ${n(0.34)} 0 0 1 ${n(0.6)} ${n(0.24)}a${n(0.26)} ${n(0.26)} 0 0 1 ${n(0.32)} ${n(0.38)}Z`;
};
const bird = (x, y, s) => `M${x - s} ${y}q${s / 2} ${-s * 0.6} ${s} 0q${s / 2} ${-s * 0.6} ${s} 0`;
const grass = (x, y) => `M${x - 30} ${y}Q${x - 30} ${y - 26} ${x - 46} ${y - 40}Q${x - 16} ${y - 32} ${x - 10} ${y}Q${x - 10} ${y - 40} ${x} ${y - 62}Q${x + 10} ${y - 40} ${x + 10} ${y}Q${x + 16} ${y - 32} ${x + 46} ${y - 40}Q${x + 30} ${y - 26} ${x + 30} ${y}`;

// ---------- Самолёт: drawn level, then tilted so that it climbs ----------
const fly = turn(500, 390, -7, 1, 20, 0);
const A = d => map(d, fly);
const AO = (x, y, r) => O(...fly(x, y).map(v => +v.toFixed(1)), r);

