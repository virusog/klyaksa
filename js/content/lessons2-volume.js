// Harder lessons on volume and perspective: two solids with their shadows, a room,
// an apple and a cherry with all the parts of light, and a street running to the horizon.
import { O, S } from '../art.js';

// ---- A small camera for the pyramid and the cube ----
// X goes right, Y up, Z away from us. Verticals stay vertical on the sheet.
const CAM = { y: 5.5, z: -10, f: 1000, cx: 410, hy: 138 };
const pr = ([X, Y, Z]) => {
  const k = CAM.f / (Z - CAM.z);
  return [Math.round(CAM.cx + X * k), Math.round(CAM.hy - (Y - CAM.y) * k)];
};
const poly = pts => pts.map((p, i) => (i ? 'L' : 'M') + p.join(' ')).join('');
const line = (...pts) => poly(pts.map(pr));
const mix = (a, b, t) => a.map((v, i) => v + (b[i] - v) * t);
// Where two sheet lines cross.
const cross = (a, b, c, d) => {
  const den = (b[0] - a[0]) * (d[1] - c[1]) - (b[1] - a[1]) * (d[0] - c[0]);
  const t = ((c[0] - a[0]) * (d[1] - c[1]) - (c[1] - a[1]) * (d[0] - c[0])) / den;
  return [Math.round(a[0] + (b[0] - a[0]) * t), Math.round(a[1] + (b[1] - a[1]) * t)];
};
// Lying strokes inside a sheet polygon: a cast shadow is hatched with them.
function lying(pts, n, inset) {
  const ys = pts.map(p => p[1]);
  const y0 = Math.min(...ys), y1 = Math.max(...ys);
  const out = [];
  for (let i = 1; i <= n; i++) {
    const y = Math.round(y0 + ((y1 - y0) * i) / (n + 1));
    const xs = [];
    pts.forEach((a, j) => {
      const b = pts[(j + 1) % pts.length];
      if ((a[1] - y) * (b[1] - y) < 0) xs.push(a[0] + ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]));
    });
    xs.sort((a, b) => a - b);
    if (xs.length >= 2 && xs[xs.length - 1] - xs[0] > 2 * inset + 14) out.push(`M${Math.round(xs[0] + inset)} ${y}H${Math.round(xs[xs.length - 1] - inset)}`);
  }
  return out;
}
// The four corners of a square lying on the table: front, right, back, left.
const corners = (cx, cz, r, turn, y = 0) => [-90, 0, 90, 180].map(a => {
  const t = ((a + turn) * Math.PI) / 180;
  return [cx + r * Math.cos(t), y, cz + r * Math.sin(t)];
});
const solids = (() => {
  // The light comes from the left and a little from behind. SUN is the run of a shadow along the
  // table for every unit of height, so every shadow in the picture obeys the same sun.
  const SUN = [0.96, -0.34];
  const shade = ([X, Y, Z]) => [X + Y * SUN[0], 0, Z + Y * SUN[1]];

  // The pyramid stands on the left, nearer to the sun.
  const PX = -2.35, PZ = 2.3;
  const A = [PX, 3.6, PZ];
  const [pF, pR, , pL] = corners(PX, PZ, 1.7, 7);
  const pyrHatch = [0.14, 0.33, 0.52, 0.7].map(s => {
    const a = mix(pF, A, s), b = mix(pR, A, s);
    return line(mix(a, b, 0.13), mix(a, b, 0.87));
  });
  const tip = pr(shade(A));
  const pyrShadow = [pr(pF), tip, pr(pR)];

  // The cube stands on the right.
  const H = 1.95, QX = 2.9, QZ = 2.2;
  const [cF, cR, cB, cL] = corners(QX, QZ, 1.42, -10);
  const [tF, tR, tB, tL] = corners(QX, QZ, 1.42, -10, H);
  const face = (u, v) => pr([cF[0] + (cR[0] - cF[0]) * u, H * v, cF[2] + (cR[2] - cF[2]) * u]);
  const cubeHatch = [-0.62, -0.31, 0, 0.31, 0.62].map(c => {
    const m = 0.09;
    const a = c >= 0 ? [c + m, m] : [m, -c + m];
    const b = c >= 0 ? [1 - m, 1 - c - m] : [1 + c - m, 1 - m];
    return poly([face(...a), face(...b)]);
  });
  // The shadow of the top square lies on the table; its last edge runs behind the cube.
  const hid = cross(pr(shade(tB)), pr(cB), pr(cR), pr(tR));
  const cubeEdge = [pr(cF), pr(shade(tF)), pr(shade(tR)), pr(shade(tB)), hid];

  // The far edge of the table, broken where the pyramid stands in front of it.
  const yT = pr([0, 0, 14.5])[1];
  const gapL = cross([0, yT], [1000, yT], pr(pL), pr(A))[0];
  const gapR = cross([0, yT], [1000, yT], pr(pR), pr(A))[0];

  // The sun sits on the ray that runs through the top of the pyramid to the tip of its shadow.
  const top = pr(A);
  const dir = [tip[0] - top[0], tip[1] - top[1]];
  const len = Math.hypot(...dir);
  const at = d => [Math.round(top[0] + (dir[0] / len) * d), Math.round(top[1] + (dir[1] / len) * d)];
  const sun = at(-165);
  let ray = '';
  for (let d = -104; d < len - 12; d += 44) if (d < -30 || d > 100) ray += poly([at(d), at(Math.min(d + 24, len))]);
  const beams = [200, 245, 290, 335, 110, 155].map(a => {
    const t = (a * Math.PI) / 180;
    return `M${Math.round(sun[0] + 54 * Math.cos(t))} ${Math.round(sun[1] + 54 * Math.sin(t))}L${Math.round(sun[0] + 76 * Math.cos(t))} ${Math.round(sun[1] + 76 * Math.sin(t))}`;
  });

  return [
    S('Свет идёт слева сверху: вот солнце. Вдали — ровный край стола с разрывом для пирамиды.',
      O(sun[0], sun[1], 40), ...beams, `M40 ${yT}H${gapL}`, `M${gapR} ${yT}H960`),
    S('Пирамида: два края основания — галочка. Вершина — высоко над серединой, к ней три ребра.',
      line(pL, pF, pR), line(pL, A), line(pF, A), line(pR, A)),
    S('Куб стоит углом к нам. Начни с ближнего ребра: от его низа два ребра уходят вдаль.',
      line(tF, cF), line(cL, cF, cR)),
    S('Боковые стойки чуть короче ближней. Верх куба — сплющенный ромб.',
      line(tL, cL), line(tR, cR), line(tL, tF, tR), line(tL, tB, tR)),
    S('Правая грань пирамиды смотрит от света: это собственная тень. К вершине штрихи короче.',
      ...pyrHatch),
    S('У куба тоже темна правая грань. Штрихи косые, все в одну сторону.',
      ...cubeHatch),
    S('Луч через вершину падает на стол: там кончик тени. Соедини его с углами основания.',
      ray, poly(pyrShadow)),
    S('Тень куба: её край на столе повторяет верх куба, а последняя линия прячется за кубом.',
      poly(cubeEdge)),
    S('Падающая тень темнее собственной. Штрихуй её гуще, лежачими линиями.',
      ...lying(pyrShadow, 3, 12).slice(0, 2), ...lying(cubeEdge.slice(0, 3).concat([pr(cR)]), 3, 12)),
  ];
})();

