const stripe = (t, sag) => {
  const p = on(DRAGON_FRONT, t), q = on(DRAGON_BELLY, t);
  return `M${xy(p)}Q${(p[0] + q[0]) / 2} ${(p[1] + q[1]) / 2 + sag} ${xy(q)}`;
};

