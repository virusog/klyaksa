// The same line seen in a mirror at x=500 (for paths made of M, L, C and Q only).
const twin = d => d.replace(/(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)/g, (m, x, y) => `${1000 - x} ${y}`);
const both = (...lines) => lines.flatMap(d => [d, twin(d)]);

// A fluffy scalloped ring that starts at the top and is symmetric left to right.
function scallops(cx, cy, rx, ry, bump, n) {
  const at = (a, k) => `${(cx + Math.sin(a) * (rx + k)).toFixed(1)} ${(cy - Math.cos(a) * (ry + k)).toFixed(1)}`;
  const da = 6.283185 / n;
  let d = `M${at(-da / 2, 0)}`;
  for (let i = 0; i < n; i++) {
    const a = -da / 2 + i * da;
    d += `C${at(a + da * 0.08, bump)} ${at(a + da * 0.92, bump)} ${at(a + da, 0)}`;
  }
  return `${d}Z`;
}

// A point on a cubic curve, as [x, y].
const on = (c, t) => [0, 1].map(k => (1 - t) ** 3 * c[0][k] + 3 * (1 - t) ** 2 * t * c[1][k] + 3 * (1 - t) * t * t * c[2][k] + t ** 3 * c[3][k]);
const xy = p => `${p[0].toFixed(1)} ${p[1].toFixed(1)}`;
const curve = c => `M${c[0].join(' ')}C${c[1].join(' ')} ${c[2].join(' ')} ${c[3].join(' ')}`;

// A row of bumps standing on a curve: sharp spikes, or soft rounded waves in one line.
function along(c, from, to, n, h, soft) {
  const out = [];
  let wave = '';
  for (let i = 0; i < n; i++) {
    const p = on(c, from + ((to - from) * i) / n), q = on(c, from + ((to - from) * (i + 1)) / n);
    const len = Math.hypot(q[0] - p[0], q[1] - p[1]) || 1;
    const top = [(p[0] + q[0]) / 2 + ((q[1] - p[1]) / len) * h, (p[1] + q[1]) / 2 - ((q[0] - p[0]) / len) * h];
    if (soft) wave += `${i ? '' : `M${xy(p)}`}Q${xy(top)} ${xy(q)}`;
    else out.push(`M${xy(p)}L${xy(top)}L${xy(q)}`);
  }
  return soft ? [wave] : out;
}

// An uneven patch with soft corners, drawn around a few points.
function patch(...p) {
  const mid = (a, b) => `${(a[0] + b[0]) / 2} ${(a[1] + b[1]) / 2}`;
  let d = `M${mid(p[p.length - 1], p[0])}`;
  p.forEach((a, i) => { d += `Q${a[0]} ${a[1]} ${mid(a, p[(i + 1) % p.length])}`; });
  return `${d}Z`;
}

