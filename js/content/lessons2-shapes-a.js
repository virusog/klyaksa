import { O, E, S, R, starD, heartD } from '../art.js';

// Mirrors a path about the sheet's middle (x = 500), so a symmetric drawing is written once.
const mir = d => {
  const out = [];
  const re = /([MLHVCSQTAZmlhvcsqtaz])([^MLHVCSQTAZmlhvcsqtaz]*)/g;
  let m;
  while ((m = re.exec(d))) {
    const c = m[1];
    const up = c === c.toUpperCase();
    const k = c.toUpperCase();
    const n = (m[2].match(/-?\d*\.?\d+/g) || []).map(Number);
    const fx = v => (up ? 1000 - v : -v);
    let r;
    if (k === 'Z') r = [];
    else if (k === 'H') r = n.map(fx);
    else if (k === 'V') r = n;
    else if (k === 'A') r = n.map((v, i) => (i % 7 === 5 ? fx(v) : i % 7 === 4 ? 1 - v : i % 7 === 2 ? -v : v));
    else r = n.map((v, i) => (i % 2 ? v : fx(v)));
    out.push(c + r.join(' '));
  }
  return out.join('');
};
// The same line on both sides of the middle.
const two = d => [d, mir(d)];

// A fluffy cloud on a flat bottom: three arcs from left to right.
const cloud = (x, y, s = 1) => {
  const p = (dx, dy) => `${Math.round(x + dx * s)} ${Math.round(y - dy * s)}`;
  const r = v => Math.round(v * s);
  return `M${p(0, 0)}A${r(40)} ${r(40)} 0 0 1 ${p(35, 60)}A${r(55)} ${r(55)} 0 0 1 ${p(130, 70)}A${r(48)} ${r(48)} 0 0 1 ${p(185, 0)}Z`;
};
// A four-pointed sparkle, symmetric on its own.
const spark = (x, y, r) => starD(x, y, r, r * 0.34, 4);
// A row of n little arcs hanging from a straight line.
// A brick joint: the top of one brick, a step down, the top of the next.
const brick = (x, y) => `M${x} ${y}h30v17h30`;
// The robot's left arm is drawn hanging straight down, then swung outwards about the shoulder.
const arm = (x, y, cx = 318, cy = 336, deg = 18) => {
  const a = deg * Math.PI / 180, dx = x - cx, dy = y - cy;
  return `${+(cx + dx * Math.cos(a) - dy * Math.sin(a)).toFixed(1)} ${+(cy + dx * Math.sin(a) + dy * Math.cos(a)).toFixed(1)}`;
};
const scallops = (x, y, w, dip, n) => `M${x} ${y}${`q${w / 2} ${dip} ${w} 0`.repeat(n)}`;

